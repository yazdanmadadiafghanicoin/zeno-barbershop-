
import pg from "pg";
import { randomUUID } from "node:crypto";

const { Pool } = pg;

const pool = new Pool({
  connectionString:
    process.env.DATABASE_URL || process.env.POSTGRES_URL,
  ssl: { rejectUnauthorized: false },
  max: 2
});

export default async function handler(req, res) {
  res.setHeader("Cache-Control", "no-store");

  if (req.method !== "POST") {
    return res.status(405).json({
      ok: false,
      error: "روش درخواست مجاز نیست."
    });
  }

  const { name, phone, service, date, time } = req.body || {};

  const services = [
    "haircut",
    "beard",
    "haircut_beard",
    "wash",
    "other"
  ];

  if (
    typeof name !== "string" ||
    !name.trim() ||
    name.trim().length > 80 ||
    typeof phone !== "string" ||
    !phone.trim() ||
    phone.trim().length > 20 ||
    !services.includes(service) ||
    typeof date !== "string" ||
    !/^\d{4}-\d{2}-\d{2}$/.test(date) ||
    typeof time !== "string" ||
    !/^([01]\d|2[01]):(00|30)$/.test(time)
  ) {
    return res.status(400).json({
      ok: false,
      error: "اطلاعات واردشده معتبر نیست."
    });
  }

  const [y, m, d] = date.split("-").map(Number);
  const checkDate = new Date(Date.UTC(y, m - 1, d));

  if (
    checkDate.getUTCFullYear() !== y ||
    checkDate.getUTCMonth() !== m - 1 ||
    checkDate.getUTCDate() !== d
  ) {
    return res.status(400).json({
      ok: false,
      error: "تاریخ معتبر نیست."
    });
  }

  const now = new Date(Date.now() + 270 * 60000);
  const today = [
    now.getUTCFullYear(),
    String(now.getUTCMonth() + 1).padStart(2, "0"),
    String(now.getUTCDate()).padStart(2, "0")
  ].join("-");

  const currentTime =
    String(now.getUTCHours()).padStart(2, "0") +
    ":" +
    String(now.getUTCMinutes()).padStart(2, "0");

  if (date < today || (date === today && time <= currentTime)) {
    return res.status(400).json({
      ok: false,
      error: "زمان انتخاب‌شده گذشته است."
    });
  }

  let client;

  try {
    client = await pool.connect();

    await client.query(`
      CREATE TABLE IF NOT EXISTS zeno_bookings (
        id TEXT PRIMARY KEY,
        customer_name VARCHAR(80) NOT NULL,
        phone VARCHAR(20) NOT NULL,
        service VARCHAR(30) NOT NULL,
        booking_date DATE NOT NULL,
        booking_time VARCHAR(5) NOT NULL,
        status VARCHAR(20) NOT NULL DEFAULT 'pending',
        created_at TIMESTAMPTZ DEFAULT NOW()
      )
    `);

    await client.query("BEGIN");

    await client.query(
      "SELECT pg_advisory_xact_lock(hashtext($1))",
      [`zeno-${date}-${time}`]
    );

    const count = await client.query(
      `SELECT COUNT(*)::int AS total
       FROM zeno_bookings
       WHERE booking_date = $1
       AND booking_time = $2
       AND status <> 'cancelled'`,
      [date, time]
    );

    if (count.rows[0].total >= 2) {
      await client.query("ROLLBACK");

      return res.status(409).json({
        ok: false,
        error: "این ساعت تکمیل شده است."
      });
    }

    const bookingId = randomUUID();

    await client.query(
      `INSERT INTO zeno_bookings
       (id, customer_name, phone, service,
        booking_date, booking_time)
       VALUES ($1, $2, $3, $4, $5, $6)`,
      [
        bookingId,
        name.trim(),
        phone.trim(),
        service,
        date,
        time
      ]
    );

    await client.query("COMMIT");

    return res.status(201).json({
      ok: true,
      message: "نوبت شما ثبت شد.",
      bookingId
    });

  } catch (error) {
    if (client) {
      await client.query("ROLLBACK").catch(() => {});
    }

    console.error("ZENO ERROR:", error);

    return res.status(500).json({
      ok: false,
      error: "خطا در ثبت نوبت."
    });

  } finally {
    if (client) client.release();
  }
}
