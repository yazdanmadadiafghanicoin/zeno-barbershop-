
import pg from "pg";
import { randomUUID } from "node:crypto";

const { Pool } = pg;

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: { rejectUnauthorized: false },
  max: 2
});

const services = [
  "haircut",
  "beard",
  "haircut_beard",
  "wash",
  "other"
];

export default async function handler(req, res) {
  res.setHeader("Cache-Control", "no-store");

  if (req.method !== "POST") {
    return res.status(405).json({
      ok: false,
      error: "فقط درخواست POST مجاز است."
    });
  }

  const { name, phone, service, date, time } = req.body || {};

  if (
    typeof name !== "string" ||
    typeof phone !== "string" ||
    !name.trim() ||
    !phone.trim() ||
    name.length > 80 ||
    phone.length > 20 ||
    !services.includes(service)
  ) {
    return res.status(400).json({
      ok: false,
      error: "اطلاعات مشتری یا خدمات معتبر نیست."
    });
  }

  if (
    typeof date !== "string" ||
    !/^\d{4}-\d{2}-\d{2}$/.test(date) ||
    typeof time !== "string" ||
    !/^([01]\d|2[01]):(00|30)$/.test(time)
  ) {
    return res.status(400).json({
      ok: false,
      error: "تاریخ یا ساعت نوبت معتبر نیست."
    });
  }

  const [year, month, day] = date.split("-").map(Number);
  const parsedDate = new Date(Date.UTC(year, month - 1, day));

  if (
    parsedDate.getUTCFullYear() !== year ||
    parsedDate.getUTCMonth() !== month - 1 ||
    parsedDate.getUTCDate() !== day
  ) {
    return res.status(400).json({
      ok: false,
      error: "تاریخ انتخاب‌شده معتبر نیست."
    });
  }

  const now = new Date();
  const afghanistanNow = new Date(
    now.getTime() + 270 * 60 * 1000
  );

  const today = [
    afghanistanNow.getUTCFullYear(),
    String(afghanistanNow.getUTCMonth() + 1).padStart(2, "0"),
    String(afghanistanNow.getUTCDate()).padStart(2, "0")
  ].join("-");

  if (date < today || (date === today && time <=
    String(afghanistanNow.getUTCHours()).padStart(2, "0") +
    ":" +
    String(afghanistanNow.getUTCMinutes()).padStart(2, "0")
  )) {
    return res.status(400).json({
      ok: false,
      error: "لطفاً یک زمان آینده انتخاب کنید."
    });
  }

  let client;

  try {
    client = await pool.connect();

    await client.query(`
      CREATE TABLE IF NOT EXISTS zeno_bookings (
        id TEXT PRIMARY KEY,
        customer_name VARCHAR(80) NOT NULL,
        phone VARCHAR(20) NOT NULL,
        service VARCHAR(30) NOT NULL,
        booking_date DATE NOT NULL,
        booking_time VARCHAR(5) NOT NULL,
        status VARCHAR(20) NOT NULL DEFAULT 'pending',
        created_at TIMESTAMPTZ DEFAULT NOW()
      )
    `);

    await client.query("BEGIN");

    // جلوگیری از ثبت هم‌زمان بیش از دو نوبت
    await client.query(
      "SELECT pg_advisory_xact_lock(hashtext($1))",
      [`zeno-${date}-${time}`]
    );

    const result = await client.query(
      `SELECT COUNT(*)::int AS total
       FROM zeno_bookings
       WHERE booking_date = $1
       AND booking_time = $2
       AND status <> 'cancelled'`,
      [date, time]
    );

    if (result.rows[0].total >= 2) {
      await client.query("ROLLBACK");

      return res.status(409).json({
        ok: false,
        error: "ظرفیت این ساعت تکمیل شده است. ساعت دیگری انتخاب کنید."
      });
    }

    const bookingId = randomUUID();

    await client.query(
      `INSERT INTO zeno_bookings
       (id, customer_name, phone, service, booking_date, booking_time)
       VALUES ($1, $2, $3, $4, $5, $6)`,
      [
        bookingId,
        name.trim(),
        phone.trim(),
        service,
        date,
        time
      ]
    );

    await client.query("COMMIT");

    return res.status(201).json({
      ok: true,
      message: "درخواست نوبت ثبت شد.",
      bookingId
    });

  } catch (error) {
    if (client) {
      await client.query("ROLLBACK").catch(() => {});
    }

    console.error("ZENO booking error:", error);

    return res.status(500).json({
      ok: false,
      error: "خطا در ثبت نوبت. لطفاً دوباره تلاش کنید."
    });

  } finally {
    if (client) client.release();
  }
}
